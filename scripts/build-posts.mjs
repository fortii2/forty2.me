import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const contentDir = path.join(root, 'content/posts');
const fields = new Set(['slug', 'date', 'category', 'draft', 'lang', 'title', 'excerpt']);

// Fixed front matter format: one scalar value per line, no nested YAML.
function parsePost(source, filename) {
  const fail = (message) => {
    throw new Error(`${filename}: ${message}`);
  };
  const normalized = source.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
  const match = /^---\n([\s\S]*?)\n---(?:\n|$)([\s\S]*)$/.exec(normalized);
  if (!match) fail('Start the file with metadata between two --- lines.');

  const metadata = {};
  for (const line of match[1].split('\n')) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const entry = /^([a-z]+):\s*(.*?)\s*$/.exec(line);
    if (!entry) fail(`Invalid metadata line: ${line}`);
    const [, key, raw] = entry;
    if (!fields.has(key)) fail(`Unknown field: ${key}`);
    if (Object.hasOwn(metadata, key)) fail(`Duplicate field: ${key}`);

    let value = raw;
    if (raw.startsWith('"')) {
      try {
        value = JSON.parse(raw);
      } catch {
        fail(`Invalid double-quoted value for ${key}.`);
      }
      if (typeof value !== 'string') fail(`${key} must be text.`);
    } else if (raw.startsWith("'")) {
      if (!/^'(?:[^']|'')*'$/.test(raw)) fail(`Invalid single-quoted value for ${key}.`);
      value = raw.slice(1, -1).replace(/''/g, "'");
    }
    metadata[key] = value;
  }

  for (const key of ['slug', 'date', 'category', 'draft', 'lang', 'title', 'excerpt']) {
    if (!metadata[key]?.trim()) fail(`Missing field: ${key}`);
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(metadata.slug)) {
    fail('slug must contain lowercase letters, numbers, and single hyphens.');
  }
  const timestamp = Date.parse(`${metadata.date}T00:00:00Z`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(metadata.date) || !Number.isFinite(timestamp) ||
      new Date(timestamp).toISOString().slice(0, 10) !== metadata.date) {
    fail('date must be a valid date in YYYY-MM-DD format.');
  }
  if (!['true', 'false'].includes(metadata.draft)) fail('draft must be true or false.');
  if (!['zh', 'en'].includes(metadata.lang)) fail('lang must be zh or en.');
  const body = match[2].trim();
  if (!body) fail('The article body is empty.');

  return { ...metadata, draft: metadata.draft === 'true', body };
}

try {
  const files = (await readdir(contentDir)).filter((file) => file.endsWith('.md')).sort();
  const posts = [];
  const slugs = new Set();
  for (const file of files) {
    const post = parsePost(await readFile(path.join(contentDir, file), 'utf8'), file);
    if (slugs.has(post.slug)) throw new Error(`${file}: Duplicate slug: ${post.slug}`);
    slugs.add(post.slug);
    posts.push(post);
  }
  posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
  const output = '// Generated by scripts/build-posts.mjs. Edit content/posts/*.md instead.\n' +
    `window.BLOG_POSTS = ${JSON.stringify(posts, null, 2)};\n`;
  await writeFile(path.join(root, 'posts.js'), output);
  console.log(`Generated posts.js with ${posts.length} article(s).`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
